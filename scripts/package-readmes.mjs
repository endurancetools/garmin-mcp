// README.md of every published package, generated from the repository README.md.
//
// npm shows the README.md found in the package directory (it is packed whatever `files` says)
// and resolves relative links against `repository.directory`, so a copy of the root README
// with relative links would 404 on npm. The apps (garmin-mcp-server, garmin-mcp-cli) get the
// root README with every relative link made absolute; the libraries get a short README that
// points to the server and the documentation.
//
//   node scripts/package-readmes.mjs           write the READMEs
//   node scripts/package-readmes.mjs --check   exit 1 if a committed README differs
//
// scripts/package-readmes.test.mjs runs the check in `pnpm check`.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = 'https://github.com/endurancetools/garmin-mcp';
export const RAW = 'https://raw.githubusercontent.com/endurancetools/garmin-mcp/main';
export const SITE = 'https://endurancetools.github.io/garmin-mcp/';
const APPS = ['apps/mcp-server', 'apps/cli'];

const root = fileURLToPath(new URL('..', import.meta.url));

const isAbsolute = (url) => /^(?:[a-z][a-z0-9+.-]*:|#|\/\/)/i.test(url);

/** Absolute URL for a link written relative to the repository root. */
export function absolutize(url) {
  if (isAbsolute(url)) return url;
  const path = posix.normalize(url.replace(/^\.\//, ''));
  const file = path.split('#')[0];
  // Images are served raw, so they render on npm too; GitHub shows files under blob/, directories under tree/.
  if (/\.(?:png|jpe?g|gif|svg|webp|avif)$/i.test(file)) return `${RAW}/${path}`;
  const isDir = path.endsWith('/') || (existsSync(join(root, file)) && statSync(join(root, file)).isDirectory());
  return `${REPO}/${isDir ? 'tree' : 'blob'}/main/${path}`;
}

/** Link targets of markdown links and images, reference definitions and HTML src/href attributes. */
const LINK = /(\]\(\s*)([^)\s]+)|^(\s{0,3}\[[^\]]+\]:\s*)(\S+)|\b((?:src|href|srcset)=")([^"]+)/gm;

/** Every relative link target in a markdown text. */
export function relativeLinks(text) {
  return [...text.matchAll(LINK)].map((m) => m[2] ?? m[4] ?? m[6]).filter((url) => !isAbsolute(url));
}

/** The root README with every relative link and image made absolute. */
export function appReadme(readme) {
  return (
    '<!-- Generated from the repository README.md by scripts/package-readmes.mjs; edit that file instead. -->\n\n' +
    readme.replace(LINK, (_, a, aUrl, b, bUrl, c, cUrl) =>
      a !== undefined ? a + absolutize(aUrl) : b !== undefined ? b + absolutize(bUrl) : c + absolutize(cUrl),
    )
  );
}

/** Short README of a library package. */
export function libraryReadme({ name, description }, dir) {
  return `<!-- Generated by scripts/package-readmes.mjs; edit that file instead. -->

# ${name}

${description}

This package is part of [Garmin MCP](${SITE}) and is installed with it; its API is internal and may change in any release. To use Garmin MCP, install the server and sign in with the CLI:

\`\`\`bash
npx -y garmin-mcp-cli login
claude mcp add garmin -- npx -y garmin-mcp-server
\`\`\`

- Documentation: [endurancetools.github.io/garmin-mcp](${SITE})
- MCP server: [garmin-mcp-server](https://www.npmjs.com/package/garmin-mcp-server)
- Source: [${dir}](${REPO}/tree/main/${dir})
- License: [MIT](${REPO}/blob/main/LICENSE)

Unofficial. Garmin and Garmin Connect are trademarks of Garmin Ltd. or its subsidiaries; this project is not affiliated with or endorsed by Garmin.
`;
}

/** Every published package directory (relative, posix) with the README it should have. */
export function expectedReadmes(base = root) {
  const readme = readFileSync(join(base, 'README.md'), 'utf8');
  const libraries = readdirSync(join(base, 'packages'), { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(base, 'packages', d.name, 'package.json')))
    .map((d) => `packages/${d.name}`)
    .sort();
  const out = new Map();
  for (const dir of APPS) out.set(dir, appReadme(readme));
  for (const dir of libraries) {
    const pkg = JSON.parse(readFileSync(join(base, dir, 'package.json'), 'utf8'));
    out.set(dir, libraryReadme(pkg, dir));
  }
  return out;
}

/** Directories whose committed README.md is missing or differs from the generated one. */
export function staleReadmes(base = root) {
  const stale = [];
  for (const [dir, text] of expectedReadmes(base)) {
    const file = join(base, dir, 'README.md');
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) stale.push(dir);
  }
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const stale = staleReadmes();
    if (stale.length) {
      console.error(`Stale README.md in ${stale.join(', ')}; run node scripts/package-readmes.mjs`);
      process.exit(1);
    }
  } else {
    for (const [dir, text] of expectedReadmes()) {
      writeFileSync(join(root, dir, 'README.md'), text);
      console.log(`wrote ${relative(root, join(root, dir, 'README.md'))}`);
    }
  }
}
